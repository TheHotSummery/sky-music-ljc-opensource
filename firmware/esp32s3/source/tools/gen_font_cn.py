#!/usr/bin/env python3
"""Rasterize simhei → 1bpp glyph table for ui_tft (no LVGL)."""

from __future__ import annotations

import pathlib
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT_H = ROOT / "components" / "ui_tft" / "include" / "font_cn.h"
OUT_C = ROOT / "components" / "ui_tft" / "font_cn_data.c"
TTF = pathlib.Path(r"C:\Windows\Fonts\simhei.ttf")
SIZE = 14


def charset() -> list[str]:
    chars: list[str] = []
    for c in range(0x20, 0x7F):
        chars.append(chr(c))
    # punctuation often in filenames / UI
    for ch in "·—…【】「」『』（）%，。.、：；！？±×÷°℃":
        chars.append(ch)
    # GB2312 Chinese (covers almost all simplified song titles)
    for qu in range(0xA1, 0xF8):
        for wei in range(0xA1, 0xFF):
            try:
                ch = bytes([qu, wei]).decode("gb2312")
            except UnicodeDecodeError:
                continue
            if len(ch) == 1:
                chars.append(ch)
    # UI extras
    for ch in "MUSIC SCORE PLAY FOLLOW RECORD VOL BANK MODE CLICK":
        chars.append(ch)
    # unique sorted by codepoint
    uniq = sorted({ch for ch in chars if ch}, key=lambda s: ord(s))
    return uniq


def raster(font: ImageFont.FreeTypeFont, ch: str) -> tuple[int, bytes]:
    # Chinese box ~SIZE; ASCII narrower
    canvas_w = SIZE + 2
    canvas_h = SIZE + 2
    img = Image.new("L", (canvas_w, canvas_h), 0)
    d = ImageDraw.Draw(img)
    d.text((0, 0), ch, font=font, fill=255)
    # tight crop horizontally, keep full height SIZE
    bbox = img.getbbox()
    if not bbox:
        w = 4 if ch == " " else max(3, SIZE // 3)
        return w, bytes((SIZE + 7) // 8 * SIZE)
    x0, y0, x1, y1 = bbox
    w = max(3, min(SIZE + 1, x1 - x0 + 1))
    # fixed height rows 0..SIZE-1 from top of canvas
    row_bytes = (w + 7) // 8
    out = bytearray(row_bytes * SIZE)
    px = img.load()
    for y in range(SIZE):
        for x in range(w):
            sx = x0 + x
            sy = y  # top-aligned in canvas
            if sx < canvas_w and sy < canvas_h and px[sx, sy] > 96:
                out[y * row_bytes + (x >> 3)] |= 0x80 >> (x & 7)
    return w, bytes(out)


def main() -> int:
    if not TTF.is_file():
        print("missing", TTF, file=sys.stderr)
        return 1
    font = ImageFont.truetype(str(TTF), SIZE)
    chars = charset()
    print(f"glyphs={len(chars)} size={SIZE}")

    bits = bytearray()
    glyphs: list[tuple[int, int, int, int]] = []  # cp, w, nbytes, off
    for ch in chars:
        cp = ord(ch)
        if cp > 0xFFFF:
            continue
        w, data = raster(font, ch)
        off = len(bits)
        bits.extend(data)
        glyphs.append((cp, w, len(data), off))

    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT_H.write_text(
        f"""#pragma once
#include <stdint.h>
#ifdef __cplusplus
extern "C" {{
#endif
#define FONT_CN_H {SIZE}
typedef struct {{
    uint16_t cp;
    uint8_t w;
    uint8_t nbytes;
    uint32_t off;
}} font_cn_glyph_t;
extern const font_cn_glyph_t font_cn_glyphs[];
extern const uint8_t font_cn_bits[];
extern const int font_cn_glyph_n;
const font_cn_glyph_t *font_cn_find(uint32_t cp);
int font_cn_draw(uint16_t *fb, int stride, int x, int y, const char *utf8,
                 uint16_t color, int max_w);
#ifdef __cplusplus
}}
#endif
""",
        encoding="utf-8",
    )

    lines = [
        "/* Auto-generated by tools/gen_font_cn.py — do not edit. */",
        '#include "font_cn.h"',
        f"const int font_cn_glyph_n = {len(glyphs)};",
        "const font_cn_glyph_t font_cn_glyphs[] = {",
    ]
    for cp, w, nb, off in glyphs:
        lines.append(f"    {{0x{cp:04X}, {w}, {nb}, {off}u}},")
    lines.append("};")
    lines.append(f"const uint8_t font_cn_bits[{len(bits)}] = {{")
    for i in range(0, len(bits), 16):
        chunk = ", ".join(f"0x{b:02X}" for b in bits[i : i + 16])
        lines.append(f"    {chunk},")
    lines.append("};")
    OUT_C.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT_H} / {OUT_C} bits={len(bits)} ({len(bits)/1024:.1f} KiB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
